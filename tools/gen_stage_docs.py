"""Regenerate docs/stages.md from every stage's --describe output (the
schema is the source of truth; this keeps the reference from drifting)."""

import json
import subprocess
import sys
from pathlib import Path

from agentic_reaxff import cli

out = ["# Stage reference", "", "Generated by `tools/gen_stage_docs.py` from `reaxff-agent <stage> --describe`.", ""]
for mod in cli._load_stage_modules():
    out += [f"## `{mod.NAME}`", "", mod.SUMMARY, ""]
    doc = (mod.__doc__ or "").strip()
    if doc:
        out += [doc, ""]
    props = (getattr(mod, "SCHEMA", None) or {}).get("properties", {})
    req = set((getattr(mod, "SCHEMA", None) or {}).get("required", []))
    if props:
        out += ["| input | type | default | description |", "|---|---|---|---|"]
        for k, v in props.items():
            t = v.get("type")
            t = " / ".join(t) if isinstance(t, list) else (t or "")
            d = v.get("default", "")
            desc = (v.get("description", "") + (" **(required)**" if k in req else "")).replace("|", "\\|")
            out.append(f"| `{k}` | {t} | {json.dumps(d) if d != '' else ''} | {desc} |")
        out.append("")
Path(__file__).resolve().parents[1].joinpath("docs", "stages.md").write_text("\n".join(out) + "\n")
print("wrote docs/stages.md")
