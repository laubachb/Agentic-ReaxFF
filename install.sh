#!/usr/bin/env bash
# Agentic-ReaxFF installer: a fresh clone -> a verified installation, in one command.
#
#   ./install.sh                                   # laptop / generic Linux
#   ./install.sh --machine dane --account pls2     # LLNL Dane
#   ./install.sh --machine dane --account pls2 \
#       --qe-bin /path/to/pw.x --pseudo-dir /path/to/upf   # register existing DFT tools
#
# Steps (each idempotent; rerun any time):
#   1. load the machine profile's modules (so the cluster MPI is visible)
#   2. pick Python >= 3.10 and create the virtual environment (.venv; uv if available)
#   3. pip install -e ".[all]"  (numpy, scipy, ase, cma, the LAMMPS wheel, tblite, matplotlib, pytest)
#   4. write env.sh: `source env.sh` gives you modules + venv + account in any new shell
#   5. reaxff-agent setup: MPI library for LAMMPS (verified by a ReaxFF single point),
#      the ReaxFF force-field library, and QE/pseudopotentials if you pass them
#   6. reaxff-agent doctor: real numerics against a stored reference
set -euo pipefail

MACHINE="generic"
PYTHON=""
VENV=".venv"
EXTRAS="all"
ACCOUNT=""
QE_BIN=""
PSEUDO_DIR=""
SKIP_SETUP=0

usage() {
  awk 'NR>1 && /^#/ {sub(/^# ?/,""); print; next} NR>1 {exit}' "$0"
  cat <<'EOF'
Options:
  --machine NAME|FILE   machine profile (dane, stampede3, generic, or a YAML path)   [generic]
  --account BANK        Slurm account written to env.sh as REAXFF_ACCOUNT
  --python EXE          Python interpreter to build the venv from (>= 3.10)
  --venv DIR            virtual environment location                                  [.venv]
  --extras LIST         pip extras (comma separated: xtb,plots,dev,molecules,jax,all)  [all]
  --qe-bin PATH         register an existing Quantum ESPRESSO pw.x
  --pseudo-dir DIR      register an existing pseudopotential directory
  --no-setup            only create the environment
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --machine) MACHINE="$2"; shift 2;;
    --account) ACCOUNT="$2"; shift 2;;
    --python) PYTHON="$2"; shift 2;;
    --venv) VENV="$2"; shift 2;;
    --extras) EXTRAS="$2"; shift 2;;
    --qe-bin) QE_BIN="$2"; shift 2;;
    --pseudo-dir) PSEUDO_DIR="$2"; shift 2;;
    --no-setup) SKIP_SETUP=1; shift;;
    -h|--help) usage; exit 0;;
    *) echo "unknown option $1"; usage; exit 2;;
  esac
done

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"
say() { printf '\033[1m==> %s\033[0m\n' "$*"; }

# ---- 1. modules from the machine profile
PROFILE="$MACHINE"
[ -f "$PROFILE" ] || PROFILE="src/agentic_reaxff/machines/profiles/${MACHINE}.yaml"
[ -f "$PROFILE" ] || { echo "no machine profile $MACHINE"; exit 2; }
MODULES="$(awk '/^modules:/{f=1;next} f&&/^[^ ]/{f=0} f&&/^ *- /{sub(/^ *- */,"");print}' "$PROFILE" | tr '\n' ' ')"
if [ -n "${MODULES// /}" ] && type module >/dev/null 2>&1; then
  say "loading modules: $MODULES"
  set +u; module load $MODULES || echo "warning: could not load all modules ($MODULES)"; set -u
fi

# ---- 2. python + venv
if [ -z "$PYTHON" ]; then
  for c in python3.12 python3.11 python3.13 python3.10 python3; do
    if command -v "$c" >/dev/null 2>&1 && "$c" -c 'import sys; sys.exit(0 if sys.version_info >= (3,10) else 1)' 2>/dev/null; then
      PYTHON="$(command -v "$c")"; break
    fi
  done
fi
[ -n "$PYTHON" ] || { echo "need Python >= 3.10 (pass --python)"; exit 2; }
say "python: $PYTHON ($("$PYTHON" -V 2>&1))"
if [ ! -x "$VENV/bin/python" ]; then
  say "creating $VENV"
  if command -v uv >/dev/null 2>&1; then uv venv -q -p "$PYTHON" "$VENV"; else "$PYTHON" -m venv "$VENV"; fi
fi
PY="$ROOT/$VENV/bin/python"
[ -x "$PY" ] || PY="$VENV/bin/python"

# ---- 3. install
say "installing agentic-reaxff[$EXTRAS] (editable)"
if command -v uv >/dev/null 2>&1; then
  uv pip install -q -p "$PY" -e ".[${EXTRAS}]"
else
  "$PY" -m pip install -q --upgrade pip
  "$PY" -m pip install -q -e ".[${EXTRAS}]"
fi

# ---- 4. env.sh
say "writing env.sh"
{
  echo "# Generated by install.sh ($(date +%F)). Usage: source $ROOT/env.sh"
  [ -n "${MODULES// /}" ] && echo "type module >/dev/null 2>&1 && module load $MODULES >/dev/null 2>&1"
  echo "source \"$(cd "$(dirname "$PY")" && pwd)/activate\""
  echo "export REAXFF_MACHINE=\"$MACHINE\""
  [ -n "$ACCOUNT" ] && echo "export REAXFF_ACCOUNT=\"$ACCOUNT\""
  echo "export OMP_NUM_THREADS=\${OMP_NUM_THREADS:-1}"
} > env.sh
# shellcheck disable=SC1091
set +u; source env.sh; set -u

if [ "$SKIP_SETUP" = 1 ]; then
  say "done (setup skipped). Next: source env.sh && reaxff-agent setup --machine $MACHINE"
  exit 0
fi

# ---- 5. setup
say "reaxff-agent setup --machine $MACHINE"
reaxff-agent setup --machine "$MACHINE" > deps_setup.json || true
"$PY" - <<'EOF'
import json
d = json.load(open("deps_setup.json"))
for c, r in d.get("results", {}).items():
    print(f"   {c:18s} {r.get('status')}" + (f"  ({r.get('error','')[:200]})" if r.get('status') == 'failed' else ""))
EOF
if [ -n "$QE_BIN" ]; then reaxff-agent setup --machine "$MACHINE" --component quantum_espresso --qe-bin "$QE_BIN" >/dev/null && echo "   quantum_espresso   registered $QE_BIN"; fi
if [ -n "$PSEUDO_DIR" ]; then reaxff-agent setup --machine "$MACHINE" --component pseudopotentials --pseudo-dir "$PSEUDO_DIR" >/dev/null && echo "   pseudopotentials   registered $PSEUDO_DIR"; fi
rm -f deps_setup.json

# ---- 6. doctor
say "reaxff-agent doctor"
reaxff-agent doctor --machine "$MACHINE" > doctor.json || true
"$PY" - <<'EOF'
import json
d = json.load(open("doctor.json"))
for c in d["checks"]:
    mark = {"ok": "ok  ", "warn": "WARN", "fail": "FAIL"}[c["status"]]
    print(f"   {mark} {c['check']:22s} {c['detail'][:90]}")
    if c.get("fix"):
        print(f"        fix: {c['fix']}")
print(f"\n   overall: {d['status']}")
EOF
rm -f doctor.json
say "done. In a new shell: source $ROOT/env.sh"
